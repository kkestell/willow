-- Writes runtime/case_data.lua and the case tables in bootstrap/core/core.wlo
-- from the Unicode 17.0 character database.
--
-- Download UnicodeData.txt, SpecialCasing.txt, and DerivedCoreProperties.txt
-- from https://www.unicode.org/Public/17.0.0/ucd/ into one directory, then run
--
--   vendor/luajit/src/luajit tools/unicode_case.lua <directory> runtime/case_data.lua bootstrap/core/core.wlo

local dir, output, core = arg[1], arg[2], arg[3]

local function lines(name)
  return io.lines(dir .. "/" .. name)
end

local utf8 = require("compiler.runtime").load({}, { "__wlo_chr" })

-- Simple mappings from UnicodeData.txt fields 13 (upper) and 14 (lower).
local upper, lower = {}, {}
for line in lines("UnicodeData.txt") do
  local fields = {}
  for field in (line .. ";"):gmatch("([^;]*);") do
    fields[#fields + 1] = field
  end
  local code = tonumber(fields[1], 16)
  if fields[13] ~= "" then
    upper[code] = tonumber(fields[13], 16)
  end
  if fields[14] ~= "" then
    lower[code] = tonumber(fields[14], 16)
  end
end

-- Runs of code points `step` apart (1 or 2) whose mappings share one delta,
-- as { first, last, step, delta }.
local function runs(map)
  local codes = {}
  for code in pairs(map) do
    codes[#codes + 1] = code
  end
  table.sort(codes)
  local result = {}
  local i = 1
  while i <= #codes do
    local first = codes[i]
    local delta, step, j = map[first] - first, nil, i
    while j < #codes do
      local gap = codes[j + 1] - codes[j]
      if map[codes[j + 1]] - codes[j + 1] ~= delta or gap > 2 or step and gap ~= step then
        break
      end
      step, j = gap, j + 1
    end
    result[#result + 1] = { first, codes[j], step or 1, delta }
    i = j + 1
  end
  return result
end

-- Unconditional full mappings that differ from the simple ones, as
-- { code, codes }.
local full_lower, full_upper = {}, {}
for line in lines("SpecialCasing.txt") do
  local data = line:gsub("#.*", "")
  local fields = {}
  for field in data:gmatch("([^;]*);") do
    fields[#fields + 1] = field:match("^%s*(.-)%s*$")
  end
  if #fields == 4 then
    local code = tonumber(fields[1], 16)
    for _, case in ipairs({ { fields[2], lower, full_lower }, { fields[4], upper, full_upper } }) do
      local codes = {}
      for hex in case[1]:gmatch("%x+") do
        codes[#codes + 1] = tonumber(hex, 16)
      end
      if #codes ~= 1 or codes[1] ~= (case[2][code] or code) then
        case[3][#case[3] + 1] = { code, codes }
      end
    end
  end
end

-- Ranges with the property, as { first, last } in the file's hex text.
local function property(name)
  local result = {}
  for line in lines("DerivedCoreProperties.txt") do
    local first, last, prop = line:match("^(%x+)%.?%.?(%x*)%s*;%s*([%w_]+)")
    if prop == name then
      result[#result + 1] = { first, last ~= "" and last or first }
    end
  end
  return result
end

local tables = {
  lower_runs = runs(lower),
  upper_runs = runs(upper),
  lower_full = full_lower,
  upper_full = full_upper,
  cased = property("Cased"),
  case_ignorable = property("Case_Ignorable"),
}

local function write(path, text)
  local file = assert(io.open(path, "wb"))
  file:write(text)
  file:close()
end

-- runtime/case_data.lua
local function run_items(list)
  local items = {}
  for i, run in ipairs(list) do
    items[i] = string.format("0x%X, 0x%X, %d, %d,", run[1], run[2], run[3], run[4])
  end
  return items
end

local function full_items(list)
  local items = {}
  for i, full in ipairs(list) do
    local text = {}
    for j, c in ipairs(full[2]) do
      text[j] = utf8(c)
    end
    items[i] = string.format("[0x%X] = %q,", full[1], table.concat(text))
  end
  table.sort(items)
  return items
end

local function range_items(list)
  local items = {}
  for i, range in ipairs(list) do
    items[i] = string.format("0x%s, 0x%s,", range[1], range[2])
  end
  return items
end

local out = {
  "-- Generated by tools/unicode_case.lua from the Unicode 17.0 character database.",
  "-- Runs are first, last, step, delta; ranges are first, last.",
}
local function emit(name, items)
  out[#out + 1] = "local " .. name .. " = {"
  for i = 1, #items, 6 do
    out[#out + 1] = "  " .. table.concat(items, " ", i, math.min(i + 5, #items))
  end
  out[#out + 1] = "}"
end
emit("__wlo_LOWER_RUNS", run_items(tables.lower_runs))
emit("__wlo_UPPER_RUNS", run_items(tables.upper_runs))
emit("__wlo_LOWER_FULL", full_items(tables.lower_full))
emit("__wlo_UPPER_FULL", full_items(tables.upper_full))
emit("__wlo_CASED", range_items(tables.cased))
emit("__wlo_CASE_IGNORABLE", range_items(tables.case_ignorable))
write(output, table.concat(out, "\n") .. "\n")

-- The case tables in core.wlo, which replace the lines from BEGIN through END.
-- Each record is fixed-width hex on its own line so core can binary-search
-- the string in place.
local BEGIN = "# Case tables generated by tools/unicode_case.lua from Unicode 17.0."
local END = "# End of the generated case tables."

local function hex(code)
  return string.format("%06X", code)
end

local records = {}
for _, name in ipairs({ "lower_runs", "upper_runs" }) do
  local lines = {}
  for i, run in ipairs(tables[name]) do
    lines[i] = table.concat({ hex(run[1]), hex(run[2]), tostring(run[3]), hex(run[1] + run[4]) }, " ")
  end
  records[name] = lines
end
for _, name in ipairs({ "lower_full", "upper_full" }) do
  local list = {}
  for i, full in ipairs(tables[name]) do
    list[i] = full
  end
  table.sort(list, function(a, b) return a[1] < b[1] end)
  local lines = {}
  for i, full in ipairs(list) do
    assert(#full[2] <= 3, "a full mapping longer than three code points")
    local fields = { hex(full[1]) }
    for j = 1, 3 do
      fields[j + 1] = hex(full[2][j] or 0)
    end
    lines[i] = table.concat(fields, " ")
  end
  records[name] = lines
end
for _, name in ipairs({ "cased", "case_ignorable" }) do
  local lines = {}
  for i, range in ipairs(tables[name]) do
    lines[i] = hex(tonumber(range[1], 16)) .. " " .. hex(tonumber(range[2], 16))
  end
  records[name] = lines
end

local block = {
  BEGIN,
  "# Runs are first, last, step, and the mapping of first; full mappings are a",
  "# code point and the up to three code points it maps to, 0 for none; ranges",
  "# are first and last. Do not edit by hand.",
}
for _, name in ipairs({ "lower_runs", "upper_runs", "lower_full", "upper_full", "cased", "case_ignorable" }) do
  block[#block + 1] = ""
  block[#block + 1] = "def case_" .. name .. "() -> str:"
  block[#block + 1] = '    return """' .. table.concat(records[name], "\n") .. "\n" .. '"""'
end
block[#block + 1] = ""
block[#block + 1] = END

local source = assert(io.open(core, "rb")):read("*a")
local start = assert(source:find(BEGIN, 1, true), "core.wlo has no case table block")
local _, stop = assert(source:find(END, start, true))
write(core, source:sub(1, start - 1) .. table.concat(block, "\n") .. source:sub(stop + 1))
