-- Writes runtime/case_data.lua from the Unicode 17.0 character database.
--
-- Download UnicodeData.txt, SpecialCasing.txt, and DerivedCoreProperties.txt
-- from https://www.unicode.org/Public/17.0.0/ucd/ into one directory, then run
--
--   vendor/luajit/src/luajit tools/unicode_case.lua <directory> runtime/case_data.lua

local dir, output = arg[1], arg[2]

local function lines(name)
  return io.lines(dir .. "/" .. name)
end

local function utf8(code)
  if code < 0x80 then
    return string.char(code)
  elseif code < 0x800 then
    return string.char(0xC0 + math.floor(code / 0x40), 0x80 + code % 0x40)
  elseif code < 0x10000 then
    return string.char(0xE0 + math.floor(code / 0x1000), 0x80 + math.floor(code / 0x40) % 0x40, 0x80 + code % 0x40)
  end
  return string.char(0xF0 + math.floor(code / 0x40000), 0x80 + math.floor(code / 0x1000) % 0x40,
    0x80 + math.floor(code / 0x40) % 0x40, 0x80 + code % 0x40)
end

-- Simple mappings from UnicodeData.txt fields 13 (upper) and 14 (lower).
local upper, lower = {}, {}
for line in lines("UnicodeData.txt") do
  local fields = {}
  for field in (line .. ";"):gmatch("([^;]*);") do
    fields[#fields + 1] = field
  end
  local code = tonumber(fields[1], 16)
  if fields[13] ~= "" then
    upper[code] = tonumber(fields[13], 16)
  end
  if fields[14] ~= "" then
    lower[code] = tonumber(fields[14], 16)
  end
end

-- Runs of code points `step` apart (1 or 2) whose mappings share one delta.
local function runs(map)
  local codes = {}
  for code in pairs(map) do
    codes[#codes + 1] = code
  end
  table.sort(codes)
  local result = {}
  local i = 1
  while i <= #codes do
    local first = codes[i]
    local delta, step, j = map[first] - first, nil, i
    while j < #codes do
      local gap = codes[j + 1] - codes[j]
      if map[codes[j + 1]] - codes[j + 1] ~= delta or gap > 2 or step and gap ~= step then
        break
      end
      step, j = gap, j + 1
    end
    result[#result + 1] = string.format("0x%X, 0x%X, %d, %d,", first, codes[j], step or 1, delta)
    i = j + 1
  end
  return result
end

-- Unconditional full mappings that differ from the simple ones.
local full_lower, full_upper = {}, {}
for line in lines("SpecialCasing.txt") do
  local data = line:gsub("#.*", "")
  local fields = {}
  for field in data:gmatch("([^;]*);") do
    fields[#fields + 1] = field:match("^%s*(.-)%s*$")
  end
  if #fields == 4 then
    local code = tonumber(fields[1], 16)
    for _, case in ipairs({ { fields[2], lower, full_lower }, { fields[4], upper, full_upper } }) do
      local codes = {}
      for hex in case[1]:gmatch("%x+") do
        codes[#codes + 1] = tonumber(hex, 16)
      end
      if #codes ~= 1 or codes[1] ~= (case[2][code] or code) then
        local text = {}
        for i, c in ipairs(codes) do
          text[i] = utf8(c)
        end
        case[3][#case[3] + 1] = string.format("[0x%X] = %q,", code, table.concat(text))
      end
    end
  end
end

local function property(name)
  local result = {}
  for line in lines("DerivedCoreProperties.txt") do
    local first, last, prop = line:match("^(%x+)%.?%.?(%x*)%s*;%s*([%w_]+)")
    if prop == name then
      result[#result + 1] = string.format("0x%s, 0x%s,", first, last ~= "" and last or first)
    end
  end
  return result
end

local out = {
  "-- Generated by tools/unicode_case.lua from the Unicode 17.0 character database.",
  "-- Runs are first, last, step, delta; ranges are first, last.",
}
local function emit(name, items)
  out[#out + 1] = "local " .. name .. " = {"
  for i = 1, #items, 6 do
    out[#out + 1] = "  " .. table.concat(items, " ", i, math.min(i + 5, #items))
  end
  out[#out + 1] = "}"
end
emit("__wlo_LOWER_RUNS", runs(lower))
emit("__wlo_UPPER_RUNS", runs(upper))
table.sort(full_lower)
table.sort(full_upper)
emit("__wlo_LOWER_FULL", full_lower)
emit("__wlo_UPPER_FULL", full_upper)
emit("__wlo_CASED", property("Cased"))
emit("__wlo_CASE_IGNORABLE", property("Case_Ignorable"))
local file = assert(io.open(output, "wb"))
file:write(table.concat(out, "\n"), "\n")
file:close()
